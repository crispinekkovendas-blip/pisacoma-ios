// Turns the Android vector drawables (res/drawable/*.xml, themselves the site's SVG icons and the
// SDA symbol) into Pisacoma/UI/Icons/IconData.swift: name → viewport, translate, paths with their
// fill/stroke attributes. The app draws them with SvgPath.swift. Run: node icons.mjs
import { readdirSync, readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const ANDROID = resolve(process.env.ANDROID ?? join(here, "../../pisacoma-android"));
const DRAWABLES = join(ANDROID, "app/src/main/res/drawable");
const OUT = resolve(here, "../Pisacoma/UI/Icons/IconData.swift");

const attr = (s, name) => { const m = s.match(new RegExp(`android:${name}="([^"]*)"`)); return m ? m[1] : null; };
const num = (s, name, d) => { const v = attr(s, name); return v == null ? d : parseFloat(v); };

const icons = [];
for (const f of readdirSync(DRAWABLES).sort()) {
  if (!f.endsWith(".xml") || f.startsWith("ic_launcher")) continue;
  const xml = readFileSync(join(DRAWABLES, f), "utf8");
  const vw = num(xml, "viewportWidth", 24), vh = num(xml, "viewportHeight", 24);
  const g = xml.match(/<group[^>]*>/);
  const tx = g ? num(g[0], "translateX", 0) : 0, ty = g ? num(g[0], "translateY", 0) : 0;
  const paths = [];
  for (const p of xml.matchAll(/<path\b[^>]*\/>/g)) {
    const s = p[0];
    const d = attr(s, "pathData");
    if (!d) continue;
    const fill = attr(s, "fillColor");
    const stroke = attr(s, "strokeColor");
    paths.push({
      d,
      fill: !!fill && fill !== "#00000000",
      evenOdd: attr(s, "fillType") === "evenOdd",
      stroke: !!stroke && stroke !== "#00000000",
      strokeWidth: num(s, "strokeWidth", 0),
      cap: attr(s, "strokeLineCap") ?? "butt",
      join: attr(s, "strokeLineJoin") ?? "miter",
    });
  }
  icons.push({ name: f.replace(/\.xml$/, ""), vw, vh, tx, ty, paths });
}

const esc = (s) => s.replace(/\\/g, "\\\\").replace(/"/g, '\\"');
let out = `// Generated by tools/icons.mjs from the Android vector drawables — do not edit.
import Foundation

struct IconPathData {
    let d: String
    let fill: Bool
    let evenOdd: Bool
    let stroke: Bool
    let strokeWidth: CGFloat
    let cap: String
    let join: String
}

struct IconData {
    let viewportWidth: CGFloat
    let viewportHeight: CGFloat
    let translateX: CGFloat
    let translateY: CGFloat
    let paths: [IconPathData]
}

enum Icons {
    static let all: [String: IconData] = [
`;
for (const i of icons) {
  out += `        "${i.name}": IconData(viewportWidth: ${i.vw}, viewportHeight: ${i.vh}, translateX: ${i.tx}, translateY: ${i.ty}, paths: [\n`;
  for (const p of i.paths) {
    out += `            IconPathData(d: "${esc(p.d)}", fill: ${p.fill}, evenOdd: ${p.evenOdd}, stroke: ${p.stroke}, strokeWidth: ${p.strokeWidth}, cap: "${p.cap}", join: "${p.join}"),\n`;
  }
  out += `        ]),\n`;
}
out += `    ]
}
`;
mkdirSync(dirname(OUT), { recursive: true });
writeFileSync(OUT, out);
console.log(`${icons.length} icons → ${OUT}`);
